export type Address = {
  street: string;
  city: string;
  state: string;
  zip: string;
};

export type Person = {
  id: string;
  first: string;
  last: string;
  email: string;
  home: Address;
  work: Address;
};

function person(
  id: string,
  first: string,
  last: string,
  email: string,
  city: string,
  state: string,
  home: [string, string],
  work: [string, string],
): Person {
  return {
    id,
    first,
    last,
    email,
    home: { street: home[0], city, state, zip: home[1] },
    work: { street: work[0], city, state, zip: work[1] },
  };
}

